def main():
    typos, texts = load_xml()
    # Remove fonts from a previous run so renamed typographies do not leave stale files.
    src = os.path.join(GEN_FONTS, "src")
    for f in os.listdir(src):
        if f.startswith(("Table_", "Font_", "Kerning_")):
            os.remove(os.path.join(src, f))
    names = []
    for typo in typos:
        name, n, size = generate_font(typo, typography_chars(typo, texts))
        names.append(name)
        print("%-32s %3d glyphs %6d bytes" % (name, n, size))
    generate_texts(typos, texts, names)
    print("%d texts, %d typographies" % (len(texts), len(typos)))


if __name__ == "__main__":
    main()
